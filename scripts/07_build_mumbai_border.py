"""Turn the cached OpenStreetMap Mumbai boundaries into a small TypeScript module for the map.

<!-- serves: J2 -->

Source: OpenStreetMap administrative boundaries via Nominatim, fetched once and cached in
data/raw/osm_mumbai_borders.json (so the demo has no live network dependency). Run this only to
regenerate frontend/src/data/mumbaiBorder.ts from that cache.

    .\\.venv\\Scripts\\python.exe scripts\\07_build_mumbai_border.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "raw" / "osm_mumbai_borders.json"
DST = ROOT / "frontend" / "src" / "data" / "mumbaiBorder.ts"
TOLERANCE = 0.0006  # degrees, roughly 65 m: invisible at any zoom the map allows


def simplify(pts: list[list[float]], tol: float) -> list[list[float]]:
    """Douglas-Peucker on [lon, lat] rings."""
    if len(pts) < 5:
        return pts

    def dist(p, a, b):
        (x, y), (x1, y1), (x2, y2) = p, a, b
        dx, dy = x2 - x1, y2 - y1
        if dx == 0 and dy == 0:
            return ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5
        t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
        return ((x - (x1 + t * dx)) ** 2 + (y - (y1 + t * dy)) ** 2) ** 0.5

    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        lo, hi = stack.pop()
        far, idx = 0.0, -1
        for i in range(lo + 1, hi):
            d = dist(pts[i], pts[lo], pts[hi])
            if d > far:
                far, idx = d, i
        if far > tol and idx > 0:
            keep[idx] = True
            stack += [(lo, idx), (idx, hi)]
    return [p for p, k in zip(pts, keep) if k]


def rings(geojson: dict) -> list[list[list[float]]]:
    polys = [geojson["coordinates"]] if geojson["type"] == "Polygon" else geojson["coordinates"]
    out = []
    for poly in polys:
        outer = simplify(poly[0], TOLERANCE)
        if len(outer) >= 4:
            out.append([[round(lat, 4), round(lon, 4)] for lon, lat in outer])
    return out


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    city = rings(data["city"]["geojson"]) + rings(data["suburban"]["geojson"])
    body = (
        "/* Generated by scripts/07_build_mumbai_border.py from OpenStreetMap administrative\n"
        "   boundaries (cached in data/raw/osm_mumbai_borders.json). [lat, lon] rings. */\n\n"
        f"export const MMR_BORDER: [number, number][][] = {json.dumps(rings(data['mmr']['geojson']), separators=(',', ':'))}\n\n"
        f"export const MUMBAI_CITY_BORDER: [number, number][][] = {json.dumps(city, separators=(',', ':'))}\n"
    )
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(body, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}: {len(body):,} bytes")


if __name__ == "__main__":
    main()
